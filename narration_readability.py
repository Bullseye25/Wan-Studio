def count_syllables(word: str) -> int:
    """Estimates syllable count using English phonetic vowel clustering rules."""
    w = word.lower().strip()
    w = re.sub(r"[^a-z]", "", w)
    if not w:
        return 1
    if len(w) <= 3:
        return 1
    # Remove silent trailing e
    if w.endswith("e") and not w.endswith("le") and not w.endswith("ee"):
        w = w[:-1]
    vowel_groups = re.findall(r"[aeiouy]+", w)
    count = len(vowel_groups)
    return max(1, count)


def calculate_flesch_reading_ease(text: str) -> float:
    """
    Computes standard Flesch Reading Ease score:
      206.835 - 1.015 * (words / sentences) - 84.6 * (syllables / words)
    Higher is easier: 90-100 very easy, 70-89 easy / standard (B1 target), <60 difficult.
    """
    words = re.findall(r"\b[A-Za-z'-]+\b", text)
    if not words:
        return 100.0
    num_words = len(words)
    sentences = [s for s in re.split(r"[.!?]+", text) if s.strip()]
    num_sentences = max(1, len(sentences))
    total_syllables = sum(count_syllables(w) for w in words)

    asl = num_words / num_sentences
    asw = total_syllables / num_words
    score = 206.835 - (1.015 * asl) - (84.6 * asw)
    return round(max(0.0, min(100.0, score)), 2)


def check_b1_readability(
    text: str,
    proper_nouns: Optional[Set[str]] = None,
    min_words: int = 5,
    max_words: int = 11,
) -> Dict[str, Any]:
    """
    Evaluates whether a voiceover line complies with CEFR B1 Plain English rules.
    Returns audit details with flagged words and suggested fixes.
    """
    cleaned = (text or "").strip()
    words = re.findall(r"\b[A-Za-z'-]+\b", cleaned)
    word_count = len(words)
    proper_set = {p.lower() for p in (proper_nouns or set())}

    issues = []
    flagged_words = []

    # 1. Word budget check (5 to 11 words)
    if word_count < min_words:
        issues.append(f"Too short ({word_count} words; target {min_words}-{max_words})")
    elif word_count > max_words:
        issues.append(f"Too long ({word_count} words; target {min_words}-{max_words})")

    # 2. Syntax / punctuation complexity check
    if ";" in cleaned or "—" in cleaned or "--" in cleaned or "(" in cleaned:
        issues.append("Complex punctuation detected (semicolons/em-dashes/parentheses not allowed in B1 voiceover)")

    # 3. Vocabulary inspection
    for w in words:
        wl = w.lower()
        if wl in proper_set or wl in B1_COMMON_WORDS:
            continue
        if wl in B1_SYNONYM_REPLACEMENTS:
            flagged_words.append(w)
            issues.append(f"Complex literary word '{w}' -> prefer '{B1_SYNONYM_REPLACEMENTS[wl]}'")
        elif count_syllables(wl) >= 4:
            flagged_words.append(w)
            issues.append(f"High-syllable word '{w}' (>3 syllables)")

    # 4. Flesch Reading Ease score
    flesch_score = calculate_flesch_reading_ease(cleaned)
    passed = len(flagged_words) == 0 and word_count <= max_words and word_count >= min_words and flesch_score >= 65.0

    return {
        "text": cleaned,
        "passed": passed,
        "flesch_score": flesch_score,
        "word_count": word_count,
        "flagged_words": flagged_words,
        "issues": issues,
        "is_b1": passed,
    }


def simplify_to_b1_rule_based(text: str, max_words: int = 10) -> str:
    """
    Performs fast, offline rule-based simplification to CEFR B1 English.
    Swaps complex literary terms with simple words and caps word length.
    """
    if not text:
        return ""
    words = text.split()
    simplified_words = []
    for w in words:
        # Strip trailing punctuation for lookup
        punct = ""
        m = re.search(r"([.,!?;:]+)$", w)
        core = w
        if m:
            punct = m.group(1)
            core = w[: -len(punct)]
        wl = core.lower()
        if wl in B1_SYNONYM_REPLACEMENTS:
            replacement = B1_SYNONYM_REPLACEMENTS[wl]
            # Match capitalization
            if core.istitle():
                replacement = replacement.capitalize()
            simplified_words.append(replacement + punct)
        else:
            simplified_words.append(w)

    reconstructed = " ".join(simplified_words)
    # Clean up duplicate spaces
    reconstructed = re.sub(r"\s+", " ", reconstructed).strip()

    # If still exceeding max_words, safely trim to complete clause
    re_words = reconstructed.split()
    if len(re_words) > max_words:
        reconstructed = " ".join(re_words[:max_words])
        if not reconstructed.endswith((".", "!", "?")):
            reconstructed += "."

    return reconstructed


def pick_sync_trigger_word(narration_text: str) -> str:
    """
    Selects the most impactful action verb from the narration line
    to act as the synchronization anchor for on-screen motion climax.
    """
    words = re.findall(r"\b[A-Za-z'-]+\b", narration_text or "")
    if not words:
        return "moves"

    # 1. Match against known action verbs
    for w in words:
        if w.lower() in ACTION_VERBS:
            return w.lower()

    # 2. Check for -ing, -ed, or -s verbal endings
    for w in words[1:]:
        wl = w.lower()
        if wl.endswith("ing") or wl.endswith("ed") or (wl.endswith("s") and len(wl) > 3):
            return wl

    # 3. Fallback to the middle word
    mid = len(words) // 2
    return words[mid].lower()
